// Raster exports and native SVG markup are derived from the vector masters.
// Requires sharp as a build tool; it is never shipped in the app.
// If sharp is outside this project, set NODE_PATH to its node_modules directory.
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const sharp = require('sharp');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assets = resolve(root, 'assets');
const brand = resolve(assets, 'brand');
const mark = await readFile(resolve(brand, 'linkup-mark.svg'), 'utf8');
const logo = await readFile(resolve(brand, 'linkup-logo.svg'), 'utf8');
const stacked = await readFile(resolve(brand, 'linkup-logo-stacked.svg'), 'utf8');
const paper = '#FAFAF6', brandBlue = '#335CFF';

function nativeSvg(svg) {
  return svg.replace(/\s(?:role|aria-labelledby)="[^"]*"/g, '').replace(/<title[^>]*>[^<]*<\/title>/g, '').replaceAll(brandBlue, 'currentColor').trim();
}
await writeFile(resolve(root, 'src/brand/artwork.ts'), '// SPDX-License-Identifier: GPL-3.0-only\n// Generated by scripts/generate-brand-assets.mjs; edit assets/brand/*.svg.\n' +
  `export const markSvg = ${JSON.stringify(nativeSvg(mark))};\nexport const logoSvg = ${JSON.stringify(nativeSvg(logo))};\n`);

const content = mark.match(/<g[\s\S]*<\/g>/)?.[0];
if (!content) throw new Error('The mark master must contain a geometry group.');
function iconSvg(scale, fill = brandBlue, background = '') {
  const x = (1024 - 640 * scale) / 2, y = (1024 - 600 * scale) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">${background ? `<rect width="1024" height="1024" fill="${background}"/>` : ''}<g transform="translate(${x} ${y}) scale(${scale})">${content.replaceAll(brandBlue, fill)}</g></svg>`;
}
async function png(svg, filename, size = 1024) {
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(resolve(assets, filename));
}
// Android uses a transparent backdrop and a larger mark within its safe area.
await png(iconSvg(1.12, brandBlue, paper), 'icon.png');
await png(iconSvg(1.32), 'android-icon.png');
await png(iconSvg(.86), 'android-icon-foreground.png');
await png(iconSvg(.86, '#000000'), 'android-icon-monochrome.png');
await sharp({ create: { width: 1024, height: 1024, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } }).png().toFile(resolve(assets, 'android-icon-background.png'));
await png(iconSvg(1.3, brandBlue, paper), 'favicon.png', 64);
await png(iconSvg(1.12), 'splash-icon.png');
await png(iconSvg(1.12, '#A4B7FF'), 'splash-icon-dark.png');
await sharp(Buffer.from(stacked)).flatten({ background: paper }).png().toFile(resolve(brand, 'linkup-preview.png'));
await sharp(Buffer.from(logo)).flatten({ background: paper }).resize({ width: 1300 }).png().toFile(resolve(brand, 'linkup-logo-preview.png'));
console.log('Generated LinkUp icons, native SVG markup, and logo previews from vector masters.');
