import { ed25519 } from '@noble/curves/ed25519.js';
import { bytesToHex, hexToBytes, utf8ToBytes } from '@noble/hashes/utils.js';

export type InviteDetails = {
  version: 1;
  publicKey: string;
  name: string;
  issuedAt: number;
  expiresAt: number;
  nonce: string;
};

export const INVITATION_TTL_MS = 7 * 24 * 60 * 60 * 1000;
export const INVITATION_FUTURE_SKEW_MS = 5 * 60 * 1000;
export const INVITATION_MAX_LENGTH = 2048;
export const INVITATION_WEB_URL = 'https://ktihana.github.io/LinkUp/';
const domain = 'common/invitation/v1\0';
const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
const invalid = () => new Error('This invitation is invalid or has been changed.');

// A small, platform-independent codec: no browser globals or Node Buffer are needed.
function encode(bytes: Uint8Array): string {
  let result = '';
  for (let i = 0; i < bytes.length; i += 3) {
    const a = bytes[i], b = bytes[i + 1], c = bytes[i + 2];
    result += alphabet[a >>> 2] + alphabet[((a & 3) << 4) | ((b ?? 0) >>> 4)];
    if (b !== undefined) result += alphabet[((b & 15) << 2) | ((c ?? 0) >>> 6)];
    if (c !== undefined) result += alphabet[c & 63];
  }
  return result;
}

function decode(value: string): Uint8Array {
  if (!/^[A-Za-z0-9_-]+$/.test(value) || value.length % 4 === 1) throw invalid();
  const bytes = new Uint8Array(Math.floor(value.length * 3 / 4));
  let bits = 0, count = 0, position = 0;
  for (const character of value) {
    bits = (bits << 6) | alphabet.indexOf(character);
    count += 6;
    if (count >= 8) {
      count -= 8;
      bytes[position++] = (bits >>> count) & 255;
      bits &= (1 << count) - 1;
    }
  }
  // Reject alternate spellings with nonzero trailing bits or padding.
  if (encode(bytes) !== value) throw invalid();
  return bytes;
}

function validateTime(now: number) {
  if (!Number.isSafeInteger(now) || now < 0 || now > Number.MAX_SAFE_INTEGER - INVITATION_TTL_MS) throw new Error('Invalid invitation time.');
}

export function isValidDisplayName(name: unknown): name is string {
  if (typeof name !== 'string' || !name || name !== name.trim() || name.length > 50 || /[\u0000-\u001f\u007f-\u009f\u202a-\u202e\u2066-\u2069]/.test(name)) return false;
  // Reject lone UTF-16 surrogates, while allowing emoji and other valid Unicode.
  for (let i = 0; i < name.length; i++) {
    const code = name.charCodeAt(i);
    if (code >= 0xd800 && code <= 0xdbff) {
      const next = name.charCodeAt(++i);
      if (!(next >= 0xdc00 && next <= 0xdfff)) return false;
    } else if (code >= 0xdc00 && code <= 0xdfff) return false;
  }
  return true;
}

function canonical(details: InviteDetails): string {
  return JSON.stringify({ version: details.version, publicKey: details.publicKey, name: details.name, issuedAt: details.issuedAt, expiresAt: details.expiresAt, nonce: details.nonce });
}

function validateDetails(value: unknown): asserts value is InviteDetails {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw invalid();
  const d = value as InviteDetails;
  if (d.version !== 1 || typeof d.publicKey !== 'string' || !/^[a-f0-9]{64}$/.test(d.publicKey) || !isValidDisplayName(d.name) || !Number.isSafeInteger(d.issuedAt) || d.issuedAt < 0 || !Number.isSafeInteger(d.expiresAt) || d.expiresAt - d.issuedAt !== INVITATION_TTL_MS || typeof d.nonce !== 'string' || !/^[a-f0-9]{32}$/.test(d.nonce)) throw invalid();
  // Identity keys generated by this protocol are canonical points in the prime-order subgroup.
  // Strict signature verification alone also permits some mixed-torsion public keys.
  try {
    const point = ed25519.Point.fromBytes(hexToBytes(d.publicKey), false);
    if (point.isSmallOrder() || !point.isTorsionFree() || bytesToHex(point.toBytes()) !== d.publicKey) throw invalid();
  } catch { throw invalid(); }
}

function extractToken(input: string): string {
  if (typeof input !== 'string' || input.length > INVITATION_MAX_LENGTH) throw invalid();
  const value = input.trim();
  // URL parsing otherwise silently removes some control characters and normalizes backslashes.
  if (/[\u0000-\u0020\u007f\\]/.test(value)) throw invalid();
  if (/^[A-Za-z0-9_-]+\.[a-f0-9]{128}$/.test(value)) return value;
  if (value.startsWith(`${INVITATION_WEB_URL}#`)) {
    const token = value.slice(INVITATION_WEB_URL.length + 1);
    if (/^[A-Za-z0-9_-]+\.[a-f0-9]{128}$/.test(token)) return token;
    throw invalid();
  }
  const native = /^common:\/\/invite\?token=([A-Za-z0-9_-]+\.[a-f0-9]{128})$/.exec(value);
  if (native) return native[1];
  const web = /^(https?:\/\/[^/?#]+)\/invite\?token=([A-Za-z0-9_-]+\.[a-f0-9]{128})$/.exec(value);
  if (!web) throw invalid();
  try {
    const url = new URL(value);
    if (!url.hostname || url.username || url.password || url.pathname !== '/invite' || url.hash) throw invalid();
  } catch { throw invalid(); }
  return web[2];
}

/** A public install page works even when the recipient has no app yet.
 * Keep the invitation in the fragment so it is not sent in the HTTP request. */
export function invitationShareUrl(input: string): string {
  return `${INVITATION_WEB_URL}#${extractToken(input)}`;
}

/** Times are Unix milliseconds. The caller supplies a fresh, cryptographically random 16-byte nonce. */
export function createInvitation(seed: Uint8Array, name: string, nonce: Uint8Array, now: number): string {
  validateTime(now);
  if (!(seed instanceof Uint8Array) || seed.length !== 32 || !(nonce instanceof Uint8Array) || nonce.length !== 16 || !isValidDisplayName(name)) throw new Error('Cannot create an invitation with these details.');
  const details: InviteDetails = { version: 1, publicKey: bytesToHex(ed25519.getPublicKey(seed)), name, issuedAt: now, expiresAt: now + INVITATION_TTL_MS, nonce: bytesToHex(nonce) };
  const json = canonical(details);
  return `${encode(utf8ToBytes(json))}.${bytesToHex(ed25519.sign(utf8ToBytes(domain + json), seed))}`;
}

/** Authenticating a key does not establish who owns it; compare the full fingerprint through a trusted channel. */
export function inspectInvitation(input: string, now: number): InviteDetails {
  validateTime(now);
  const token = extractToken(input);
  const [payload, signature] = token.split('.');
  let details: unknown, json: string;
  try {
    json = new TextDecoder('utf-8', { fatal: true }).decode(decode(payload));
    details = JSON.parse(json);
  } catch { throw invalid(); }
  validateDetails(details);
  // Fixed field order and exact serialization reject duplicate keys, extra fields, and alternate JSON encodings.
  if (canonical(details) !== json || !ed25519.verify(hexToBytes(signature), utf8ToBytes(domain + json), hexToBytes(details.publicKey), { zip215: false })) throw invalid();
  if (details.issuedAt > now + INVITATION_FUTURE_SKEW_MS) throw new Error('This invitation was created in the future. Check your device clock.');
  if (details.expiresAt <= now) throw new Error('This invitation has expired. Ask for a new one.');
  return details;
}

export function fingerprint(publicKey: string): string {
  if (typeof publicKey !== 'string' || !/^[a-f0-9]{64}$/i.test(publicKey)) throw new Error('Invalid identity key.');
  return publicKey.toUpperCase().match(/.{8}/g)!.join(' ');
}
